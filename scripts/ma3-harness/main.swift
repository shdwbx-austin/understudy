// Writes the grandMA3 export Lua for a few setups as a Lua table (plans.lua), for console.lua
// to run against a mock console. Usage: ma3-harness-gen <out.lua>
import Foundation
import UnderstudyCore

let rate = FrameRate.fps30
func f(_ tc: String) -> Int { Timecode(tc)!.frameIndex(at: .fps30) }

// Two songs on the set, markers in both and one off the set.
let allsWell = Song(name: "ALL'S WELL", start: Timecode("01:00:00:00")!, duration: 200)
let bones = Song(name: "BONES", start: Timecode("11:00:00:00")!, duration: 150)
let songs = ExportSong.set(TimelineLayout(ordered: [allsWell, bones], rate: rate, gap: 2))
let markers = [
    Marker(frame: f("01:00:24:16"), kind: .choreo, label: "Verse \"one\""),
    Marker(frame: f("01:00:30:00"), kind: .choreo, label: "It's on"),
    Marker(frame: f("01:00:47:16"), kind: .lighting, label: "Drop"),
    Marker(frame: f("11:00:10:00"), kind: .choreo),
    Marker(frame: f("11:00:20:00"), kind: .pyro, label: "Gerbs"),
    Marker(frame: f("05:00:00:00"), kind: .notes),
]

func perSong(choreo write: MA3ExportSettings.Write) -> MA3ExportSettings {
    var s = MA3ExportSettings()
    s.sequences = .perSongAndType
    s.songOffset = 20
    s.timecodes = .perSong
    s.pages = .perSong
    s.page = 3
    s.latencyFrames = 1
    s.types["choreo"] = .init(exec: 201, source: .executor, write: write)
    s.types["lighting"] = .init(exec: 202)
    return s
}

let plans: [(String, MA3Plan)] = [
    ("override", MA3Plan.make(markers, songs: songs, rate: rate, types: .defaults, settings: perSong(choreo: .override),
                              sequenceStart: 4225, timecodeStart: 15, name: "Understudy · Summer")),
    ("merge", MA3Plan.make(markers, songs: songs, rate: rate, types: .defaults, settings: perSong(choreo: .merge),
                           sequenceStart: 4225, timecodeStart: 15, name: "Understudy · Summer")),
    ("single", MA3Plan.make(markers, songs: songs, rate: rate, types: .defaults, settings: MA3ExportSettings(),
                            sequenceStart: 1001, timecodeStart: 101, name: "Understudy · Summer")),
    // 60 markers on one song: several cue and event batches.
    ("batches", MA3Plan.make((0..<60).map { Marker(frame: f("01:00:10:00") + $0 * 30, kind: .audio) }, songs: songs, rate: rate,
                             types: .defaults, settings: MA3ExportSettings(), sequenceStart: 2001, timecodeStart: 201, name: "Understudy · Many")),
]

func long(_ s: String) -> String { "[==[" + s + "]==]" }

var out = "-- Generated by scripts/ma3-harness/main.swift\nreturn {\n"
for (name, plan) in plans {
    out += "  \(name) = {\n    steps = {\n"
    for step in MA3Deploy.steps(plan) { out += "      " + long(step.command) + ",\n" }
    out += "    },\n    plugin = " + long(MA3Deploy.pluginLua(plan)) + ",\n"
    out += "    rawPerSecond = \(Int(MA3Deploy.rawPerSecond)),\n  },\n"
}
out += "}\n"
try out.write(toFile: CommandLine.arguments[1], atomically: true, encoding: .utf8)
print("Wrote \(plans.count) plans to \(CommandLine.arguments[1])")
